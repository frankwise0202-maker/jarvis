// The Public Suffix List (https://publicsuffix.org), used for site permissions: which hosts belong
// to one "site" (registrable domain). Chrome does not expose its own copy to extensions, so a dated
// snapshot is vendored in extension/vendor/public_suffix_list.dat (ICANN and private sections,
// Mozilla Public License 2.0) and turned into extension/src/background/psl-data.js:
//
//   node extension/build/psl.mjs          regenerates psl-data.js from the vendored list
//
// The unit tests check that psl-data.js matches the vendored list (test/extension/unit/build.test.mjs).

import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import url, { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
export const PSL_SOURCE = path.resolve(HERE, '..', 'vendor', 'public_suffix_list.dat');
export const PSL_MODULE = path.resolve(HERE, '..', 'src', 'background', 'psl-data.js');

/** A rule in the form hosts are compared in (lowercase ASCII; IDN labels in punycode). */
function toAscii(rule) {
  const bang = rule.startsWith('!');
  const body = bang ? rule.slice(1) : rule;
  const labels = body.split('.').map((l) => (l === '*' ? l : url.domainToASCII(l) || ''));
  if (labels.some((l) => !l)) return null;
  return `${bang ? '!' : ''}${labels.join('.')}`.toLowerCase();
}

/** The rules of a public_suffix_list.dat text, both sections, deduplicated and sorted. */
export function parsePsl(text) {
  const rules = new Set();
  for (const raw of String(text).split('\n')) {
    const line = raw.trim().split(/\s/)[0];
    if (!line || line.startsWith('//')) continue;
    const rule = toAscii(line);
    if (rule) rules.add(rule);
  }
  return [...rules].sort();
}

/** The generated module's source. */
export function pslModuleSource(rules, { snapshot = '' } = {}) {
  return `// Generated by extension/build/psl.mjs from extension/vendor/public_suffix_list.dat${snapshot ? ` (${snapshot})` : ''}.
// Do not edit: regenerate with \`node extension/build/psl.mjs\`.
// The Public Suffix List is licensed under the Mozilla Public License 2.0 (https://mozilla.org/MPL/2.0/).
export default ${JSON.stringify(rules.join(' '))};
`;
}

export function generatePslModule() {
  return pslModuleSource(parsePsl(readFileSync(PSL_SOURCE, 'utf8')), { snapshot: 'snapshot of 2025-12-28' });
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const src = generatePslModule();
  writeFileSync(PSL_MODULE, src);
  console.log(`wrote ${path.relative(process.cwd(), PSL_MODULE)} (${src.length.toLocaleString('en-US')} bytes)`);
}
